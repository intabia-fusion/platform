# Seal the live Secrets of a stand (or platform-base) into a values overlay with SealedSecret
# manifests. The next deploy renders them instead of the plain secrets. The controller's key is
# cluster-specific: the overlay is only valid for the cluster it was sealed on.
set -euo pipefail
TARGET="${1:?usage: seal-secrets.sh <stand|base> [runtime]}"; shift || true
[ $# -ge 1 ] && case "$1" in k3d|kind|existing) STAND_RUNTIME="$1"; shift ;; esac
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=lib.sh
source "$SCRIPT_DIR/lib.sh"

command -v kubeseal >/dev/null 2>&1 || \
  die "kubeseal is not installed: brew install kubeseal (or download it from the sealed-secrets release)"

ensure_cluster
kc -n kube-system get deployment sealed-secrets-controller >/dev/null 2>&1 || \
  die "sealed-secrets controller is not running in kube-system: SEALED_SECRETS=1 pnpm -w stand:base:up"

if [ "$TARGET" = base ]; then
  NS="$BASE_NAMESPACE"
  RELEASE="platform-base"
  OUT="$K8S_DIR/stands/base/sealed.yaml"
else
  NS="$(stand_namespace "$TARGET")"
  RELEASE="fusion-$TARGET"
  OUT="$K8S_DIR/stands/$TARGET/sealed.yaml"
fi
[ -n "$NS" ] || die "cannot resolve the namespace for '$TARGET'"

log "reading the release manifest of $RELEASE in $NS"
SECRETS="$(helmc -n "$NS" get manifest "$RELEASE" | python3 -c '
import re, sys
for doc in sys.stdin.read().split("\n---"):
    if re.search(r"^kind: Secret$", doc, re.M):
        m = re.search(r"^  name: (\S+)$", doc, re.M)
        if m:
            print(m.group(1))
')"
[ -n "$SECRETS" ] || die "the release has no Secret resources; deploy it with plain secrets first"

TMP="$(mktemp -t sealed.XXXXXX.yaml)"
trap 'rm -f "$TMP"' EXIT
for name in $SECRETS; do
  if ! kc -n "$NS" get secret "$name" >/dev/null 2>&1; then
    warn "secret $name is not in the cluster yet - skipped"
    continue
  fi
  echo "---" >> "$TMP"
  kc -n "$NS" get secret "$name" -o yaml | kubeseal \
    --context "$KUBE_CONTEXT" \
    --controller-name sealed-secrets-controller \
    --controller-namespace kube-system \
    --format yaml | sed '/^---$/d' >> "$TMP"
  log "sealed $name"
done

[ -s "$TMP" ] || die "nothing was sealed"

python3 - "$TMP" "$OUT" <<'PY'
import sys
from pathlib import Path

sealed = Path(sys.argv[1]).read_text().strip()
indented = "\n".join("    " + line if line.strip() != "" else "" for line in sealed.splitlines())
overlay = f"""# Generated by `pnpm -w stand:seal`: decryptable only by this cluster's sealed-secrets key.
sealedSecrets:
  enabled: true
  manifests: |
{indented}
"""
Path(sys.argv[2]).write_text(overlay)
print(f"wrote {sys.argv[2]} ({len(sealed.splitlines())} lines)")
PY

log "overlay written: $OUT"
echo "next: pnpm -w stand:deploy $TARGET --no-push (the overlay is picked up automatically)"